export function getRandomCards(count) {
  const shuffled = [...MAJOR_ARCANA].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map(c => ({
    ...c,
    reversed: Math.random() > 0.75,
  }));
}
